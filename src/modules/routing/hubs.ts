/**
 * Дополнительные узлы: для некоторых регионов до малого города удобнее ехать
 * не через свой центр, а через соседний крупный узел.
 */
export const NEIGHBOUR_HUBS: Record<string, string[]> = {
  'ярославская область': ['Ростов Великий', 'Рыбинск'],
  'ивановская область': ['Кострома'],
  'владимирская область': ['Нижний Новгород'],
  'костромская область': ['Ярославль'],
  'тверская область': ['Великий Новгород'],
};

/** Строка региона у Туту бывает составной: «городской округ Тобольск, Тюменская область». */
function normalizeRegion(region: string): string {
  return region.toLowerCase().split(',').map((part) => part.trim()).at(-1) ?? '';
}

/**
 * Возвращает города-кандидаты для пересадки: сначала центр региона, затем соседние узлы.
 * Пустой массив означает, что регион неизвестен — тогда кандидатов ищем иначе.
 */
export function resolveHub(region: string | undefined, exclude: string[] = []): string[] {
  if (!region) return [];

  const key = normalizeRegion(region);
  const hubs = [REGION_HUBS[key], ...(NEIGHBOUR_HUBS[key] ?? [])].filter(Boolean) as string[];
  const skip = exclude.map((city) => city.toLowerCase());

  return hubs.filter((city) => !skip.includes(city.toLowerCase()));
}
